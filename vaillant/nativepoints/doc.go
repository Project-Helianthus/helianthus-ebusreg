// Package nativepoints is the native point catalog of the Vaillant controller
// register service and the boiler and heat-pump register service: one row per
// device class and canonical name, joined from the repository's name
// annotations, the controller register matrix by family, the Wire and Decode
// columns of the published register map, codec dictionaries and scalar
// interpreters.
//
// Controller rows cover every named register of the opcode 0x02 groups,
// including the local parameter group 0x0A, and of the opcode 0x06 device
// groups, whose universal names apply to registers 0x0001 to 0x0004 of every
// group. A controller location takes its codec, unit and enumeration from the
// register matrix row of its controller family and otherwise from the map,
// whose layout also applies to a family the matrix does not list unless the
// map reads the register on one family only; a matrix row that leaves the
// unit blank keeps the map's unit. A register whose layout the documentation
// leaves open has no codec and stays native and named, and a wire type alone
// does not make a register numeric.
//
// Each row says whether its value may be exported. A row is exportable only
// when its name is final, its value class is numeric, its native unit converts
// to SI, its codec is one Decode implements and it is not a pressure without a
// documented reference; otherwise the row carries the first failing reason.
// The evidence grade of the sources is Hypothesis on every row and is not the
// gate. Codes, access codes and identifiers are never exportable.
//
// Decode turns a retained raw reply of an exportable row into an exact native
// value and its exact SI value. It refuses withheld rows, non-finite values,
// codec sentinels and replies of the wrong length with a typed DecodeError.
// DecodeNative turns a retained raw reply of any row with a known codec into
// its exact native value: a number, a Boolean, an enumeration code with its
// documented label (empty for a code without a candidate label), a date or a
// time of packed binary-coded decimal bytes, a firmware version or a text.
// The Boolean and enumeration readings follow the value class each
// location's own documentation states, so a location that states neither
// keeps its integer. It refuses a wrong width, a Boolean or date out of range,
// a date or time byte that is not binary-coded decimal and a codec sentinel
// with the same typed error. Point.ForLocation narrows a row to one location,
// for example to one controller family's enumeration, and gives it the value
// class DecodeNative decodes that location as. The package performs no bus
// traffic.
//
// The catalog table is generated by scripts/generate_native_points.py; run it
// with --check to compare the committed table with the sources.
